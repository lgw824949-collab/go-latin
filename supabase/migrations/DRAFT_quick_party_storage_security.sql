-- Private bucket; authenticated users upload only to their own UUID folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('quick-party-posters', 'quick-party-posters', false, 5242880,
  array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

create policy "organizers upload to own quick-party folder"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'quick-party-posters'
  and (storage.foldername(name))[1] = auth.uid()::text
  and lower(storage.extension(name)) in ('jpg','jpeg','png','webp')
);

