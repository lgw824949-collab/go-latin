-- Restrict poster_path to submitting user's own bucket prefix.
-- Note: existence, MIME content, orphan cleanup, duplicate prevention and
-- rate limiting require a server-side submission service before enabling writes.
create or replace function public.quick_party_validate_poster_path()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if new.poster_path not like new.submitted_by::text || '/%' then
    raise exception 'Poster must belong to submitting organizer';
  end if;
  return new;
end;
$$;
create trigger quick_party_poster_owner_check
before insert on public.quick_party_submissions
for each row execute function public.quick_party_validate_poster_path();

